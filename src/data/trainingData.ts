export function generateInitialSchedule(): WeeklySchedule {
  const days = ['Monday', 'Tuesday', 'Wednesday', 'Thursday', 'Friday', 'Saturday', 'Sunday'] as const;
  const scheduleDays: Record<string, any> = {};

  days.forEach(day => {
    let activityType: 'TRAINING' | 'TEAM_UNIT' | 'RECOVERY' | 'REST' = 'TRAINING';
    let teamSession = undefined;

    if (day === 'Wednesday') {
      activityType = 'TEAM_UNIT';
      teamSession = {
        id: `team_${day}`,
        unitName: 'Batting Unit' as const,
        category: 'BATTING' as const,
        day,
        intensity: 'Normal' as const,
        coachId: 'COACH_02',
      };
    } else if (day === 'Saturday') {
      activityType = 'TEAM_UNIT';
      teamSession = {
        id: `team_${day}`,
        unitName: 'Fielding Unit' as const,
        category: 'FIELDING' as const,
        day,
        intensity: 'Normal' as const,
        coachId: 'COACH_05',
      };
    } else if (day === 'Sunday') {
      activityType = 'RECOVERY';
    }

    scheduleDays[day] = {
      day,
      activityType,
      teamSession,
      individualAssignments: [],
      notes: day === 'Sunday' ? 'Squad Recovery & Hydrotherapy' : 'Scheduled Net Practice',
    };
  });

  return {
    weekNumber: 1,
    days: scheduleDays,
  };
}
